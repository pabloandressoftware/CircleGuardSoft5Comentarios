package com.circleguard.promotion.service;

import com.circleguard.promotion.model.graph.CircleNode;
import com.circleguard.promotion.model.graph.UserNode;
import com.circleguard.promotion.repository.graph.CircleNodeRepository;
import com.circleguard.promotion.repository.graph.UserNodeRepository;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

/** Reglas de los circulos de contacto, sin base de datos (HU-13). */
class CircleServicesTest {

    private final CircleNodeRepository circles = mock(CircleNodeRepository.class);
    private final UserNodeRepository users = mock(UserNodeRepository.class);
    private final HealthStatusService health = mock(HealthStatusService.class);
    private final CircleService circleService = new CircleService(circles, health);

    private UserNode user(String id, String status) {
        return UserNode.builder().anonymousId(id).status(status).build();
    }

    @Test
    void createCircleGeneratesMeshInviteCode() {
        when(circles.existsByInviteCode(anyString())).thenReturn(true, false);
        when(circles.save(any(CircleNode.class))).thenAnswer(i -> i.getArgument(0));

        CircleNode c = circleService.createCircle("Lab", "loc-1");

        assertTrue(c.getInviteCode().startsWith("MESH-"));
        assertEquals(9, c.getInviteCode().length());
        assertTrue(c.getIsActive());
    }

    @Test
    void joinAndAddMemberFailWhenGraphReturnsNothing() {
        when(circles.joinCircle("u", "X")).thenReturn(Optional.empty());
        when(circles.addUserToCircle("u", 1L)).thenReturn(Optional.empty());
        assertThrows(RuntimeException.class, () -> circleService.joinCircle("u", "X"));
        assertThrows(RuntimeException.class, () -> circleService.addMember(1L, "u"));

        CircleNode c = new CircleNode();
        when(circles.joinCircle("u", "OK")).thenReturn(Optional.of(c));
        when(circles.addUserToCircle("u", 2L)).thenReturn(Optional.of(c));
        when(circles.findCirclesByUser("u")).thenReturn(List.of(c));
        assertSame(c, circleService.joinCircle("u", "OK"));
        assertSame(c, circleService.addMember(2L, "u"));
        assertEquals(1, circleService.getUserCircles("u").size());
    }

    @Test
    void invalidatingACircleReevaluatesItsMembers() {
        CircleNode c = new CircleNode();
        c.setIsValid(true);
        c.setMembers(Set.of(user("a", "ACTIVE")));
        when(circles.findById(1L)).thenReturn(Optional.of(c));

        circleService.toggleCircleValidity(1L);

        assertFalse(c.getIsValid());
        verify(health).resolveStatus("a");
        circleService.toggleCircleValidity(1L); // vuelve a ser valido: no reevalua
        verify(health, times(1)).resolveStatus("a");
    }

    @Test
    void forceFencePromotesOnlyActiveMembersToProbable() {
        CircleNode c = new CircleNode();
        c.setName("c");
        c.setMembers(Set.of(user("a", "ACTIVE"), user("b", "SUSPECT")));
        when(circles.findById(1L)).thenReturn(Optional.of(c));

        circleService.forceFenceCircle(1L);

        assertTrue(c.getForceFence());
        verify(health).updateStatus("a", "PROBABLE");
        verify(health, never()).updateStatus(eq("b"), anyString());
        when(circles.findById(9L)).thenReturn(Optional.empty());
        assertThrows(RuntimeException.class, () -> circleService.forceFenceCircle(9L));
        assertThrows(RuntimeException.class, () -> circleService.toggleCircleValidity(9L));
    }

    // ---------- AutoCircleService ----------
    @Test
    void autoCircleIsCreatedOnlyAfterOneHourTogetherAndNotTwice() {
        CircleService mockCircleService = mock(CircleService.class);
        AutoCircleService auto = new AutoCircleService(users, circles, mockCircleService);

        auto.evaluateEncounter(null, "b");
        auto.evaluateEncounter("a", "a");
        when(users.getCumulativeEncounterDuration("a", "b")).thenReturn(600L);
        auto.evaluateEncounter("a", "b");
        verify(circles, never()).save(any());

        when(users.getCumulativeEncounterDuration("a", "b")).thenReturn(3600L);
        when(circles.findCommonCircles("a", "b")).thenReturn(List.of());
        auto.evaluateEncounter("a", "b");
        verify(circles).save(any(CircleNode.class));
        verify(mockCircleService, times(2)).joinCircle(anyString(), startsWith("AUTO-"));

        CircleNode existing = new CircleNode();
        existing.setIsAutoGenerated(true);
        when(circles.findCommonCircles("a", "b")).thenReturn(List.of(existing));
        auto.evaluateEncounter("a", "b");
        verify(circles, times(1)).save(any()); // no se crea otro
    }

    private static String startsWith(String p) {
        return org.mockito.ArgumentMatchers.startsWith(p);
    }
}
